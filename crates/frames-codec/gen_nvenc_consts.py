#!/usr/bin/env python3
"""Emits src/nvenc/v<major>/consts.rs: the GUIDs and struct-version macros of
an NVENC header, which bindgen cannot translate (static const values and
function-like macros). Run from crates/frames-codec after
gen_nvenc_bindings.sh, as `gen_nvenc_consts.py 13.1` (or 12.2)."""

import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
api = sys.argv[1]
header = (here / "third_party" / f"nvEncodeAPI-{api}.h").read_text()
out = [
    f"// Generated by gen_nvenc_consts.py from third_party/nvEncodeAPI-{api}.h. Do not edit.",
    "#![allow(dead_code)]",
    "use super::sys::{GUID, NVENCAPI_VERSION};",
    "",
    "const fn struct_version(version: u32) -> u32 {",
    "    NVENCAPI_VERSION | (version << 16) | (0x7 << 28)",
    "}",
    "",
]
guid = re.compile(
    r"static const GUID (\w+)\s*=\s*\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*\{([^}]*)\}\s*\};",
    re.S,
)
for name, d1, d2, d3, rest in guid.findall(header):
    d4 = ", ".join(byte.strip() for byte in rest.split(","))
    out.append(
        f"pub const {name}: GUID = GUID {{ Data1: {d1}, Data2: {d2}, Data3: {d3}, Data4: [{d4}] }};"
    )
out.append("")
version = re.compile(
    r"#define (\w+_VER)\s+\(?NVENCAPI_STRUCT_VERSION\((\d+)\)(\s*\|\s*\(\s*1u\s*<<\s*31\s*\)\s*\))?"
)
for name, number, high in version.findall(header):
    value = f"struct_version({number})" + (" | (1 << 31)" if high else "")
    out.append(f"pub const {name}: u32 = {value};")
(here / "src" / "nvenc" / f"v{api.split('.')[0]}" / "consts.rs").write_text("\n".join(out) + "\n")
